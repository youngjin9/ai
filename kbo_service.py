def get_kbo_rankings():
    """실시간 네이버 검색 테이블에서 KBO 팀 순위를 스크랩하고, 실패 시 최신 백업 데이터 반환"""
    try:
        url = 'https://search.naver.com/search.naver?query=KBO+%EC%88%9C%EC%9C%84'
        r = requests.get(url, headers=HEADERS, timeout=4)
        if r.status_code == 200:
            soup = BeautifulSoup(r.text, 'html.parser')
            tbl = soup.find('table', {'class': 'tb_type2'})
            if tbl:
                rows = []
                for tr in tbl.find_all('tr'):
                    tds = [c.get_text(strip=True) for c in tr.find_all(['th', 'td'])]
                    if tds and tds[0] != '순위' and len(tds) >= 8:
                        rows.append({
                            "순위": int(tds[0]) if tds[0].isdigit() else tds[0],
                            "팀명": tds[1],
                            "경기": int(tds[2]) if tds[2].isdigit() else tds[2],
                            "승": int(tds[3]) if tds[3].isdigit() else tds[3],
                            "무": int(tds[4]) if tds[4].isdigit() else tds[4],
                            "패": int(tds[5]) if tds[5].isdigit() else tds[5],
                            "승률": float(tds[6]) if re.match(r'^\d+\.\d+$', tds[6]) else tds[6],
                            "게임차": tds[7],
                            "연속": tds[8] if len(tds) > 8 else "-",
                            "최근10경기": tds[9] if len(tds) > 9 else "-"
                        })
                if len(rows) >= 8:
                    return pd.DataFrame(rows)
    except Exception as e:
        pass
    return pd.DataFrame(DEFAULT_TEAM_RANKINGS)

